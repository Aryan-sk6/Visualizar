#!/usr/bin/env node
// Generates hooks/translate.js from ../src/translate.js so the mod reuses
// visualizar's phrases. A mod runs in a sandbox with no Node, so the two Node
// dependencies (node:path, process.env) are swapped for small stand-ins.
//   node mod/build.mjs          write hooks/translate.js
//   node mod/build.mjs --check  exit 1 if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(here, '..', 'src', 'translate.js'), 'utf8');

const swaps = [
  [`import path from 'node:path';`, `import path from './pathshim.js';`],
  [`import { clip } from './model.js';`, `import { clip } from './pathshim.js';`],
  [`process.env.HOME`, `(typeof process === 'undefined' ? undefined : process.env.HOME)`],
];
let out = src;
for (const [from, to] of swaps) {
  if (!out.includes(from)) throw new Error(`translate.js no longer contains: ${from}`);
  out = out.split(from).join(to);
}
out = `// GENERATED by mod/build.mjs from src/translate.js. Do not edit.\n${out}`;

const target = path.join(here, 'hooks', 'translate.js');
if (process.argv.includes('--check')) {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (have !== out) {
    console.error('mod/hooks/translate.js is out of date; run: node mod/build.mjs');
    process.exit(1);
  }
} else {
  fs.writeFileSync(target, out);
  console.log('wrote', path.relative(process.cwd(), target));
}
